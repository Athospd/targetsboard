# The marks assemble.py cuts from: the hook, played first, and the short.
hook <- function(on) ev("hook", on = on)
short <- function(on, text = "") ev("short", on = on, text = text)
# A native tooltip isn't in the screencast: it's drawn in post, from the
# element's title, below it.
tooltip <- function(sel, text = NULL) {
  if (is.null(text)) text <- js(sprintf("document.querySelector(\"%s\").title", sel))
  r <- rect(sel)
  ev("tooltip", on = TRUE, text = text, x = r[1] + r[3] / 2, y = r[2] + r[4] + 8)
}
tooltip_off <- function() ev("tooltip", on = FALSE)
# A native select's list isn't in the screencast either: click it, then
# choose as a pick would.
choose <- function(sel, value) {
  click(sel, dur = 0.5)
  hold(0.4)
  js(sprintf("(() => { const s = document.querySelector('%s'); s.value = '%s'; s.dispatchEvent(new Event('change', { bubbles: true })); })()",
             sel, value))
}
base <- function(id) sprintf(".react-flow__node[data-id='%s'] .base-node", id)
status_is <- function(id, status) has(sprintf(".react-flow__node[data-id='%s'] .tb-status-%s", id, status))
run_summary <- "#board-run_summary-summary"
preview <- "#board-preview-sidebar"
content <- "#board-preview-content"
shows <- function(what, timeout = 20) {
  until(sprintf("(() => { const p = document.querySelector('%s'); return !!p && !p.querySelector('.recalculating') && %s; })()",
                preview, what), timeout)
}
shows_cut <- function(what, timeout = 30) { skip(TRUE); shows(what, timeout); hold(0.25); skip(FALSE) }
# The preview shows this target's value: its name heads the pane, and `what`
# is in it (the last target's stays under the spinner until then).
value_of <- function(name, what = "true") {
  sprintf("p.querySelector('.tb-preview-name')?.textContent.trim() === '%s' && %s", name, what)
}
tab <- function(value) sprintf("#board-view .nav-link[data-value='%s']", value)
menu <- function(id, action) {
  click(node(id), button = "right")
  until(has(".tb-node-menu"), 5)
  hold(0.5)
  click(sprintf(".tb-node-menu [data-action='%s']", action), dur = 0.4)
}
confirm_invalidate <- function() {
  until(has(".modal.show [id$='invalidate_confirm']"), 5)
  until("getComputedStyle(document.querySelector('.modal.show .modal-dialog')).transform === 'none'", 3)
  hold(0.5)
  click(".modal.show [id$='invalidate_confirm']", dur = 0.4)
  until("!document.querySelector('.modal.show')", 5)
  hold(0.3); dismiss()
}

