const TITLES = {
  pattern: 'Pattern: dynamic branching',
  file: 'File target (format = "file")',
  quarto: 'Quarto report',
  rmarkdown: 'R Markdown report',
  function: 'Function',
  object: 'Object',
};

// The kind a target shows: a report first (a rendered document, even
// branched), then a pattern, a file, a function or an object; a plain
// target has none. `type` is tar_visnetwork()'s; `kind` comes from the
// target's definition (target_kinds()).
export const targetKind = (type, kind) => {
  if (kind === 'quarto' || kind === 'rmarkdown') return kind;
  if (type === 'pattern') return 'pattern';
  if (kind === 'file') return 'file';
  if (type === 'function' || type === 'object') return type;
  return null;
};

const TypeIcon = ({ kind }) => {
  if (!kind) return null;
  const shape = ICONS[kind === 'quarto' || kind === 'rmarkdown' ? 'report' : kind];
  return (
    <span className="tb-type-icon" data-kind={kind} title={TITLES[kind]}>
      <svg viewBox="0 0 16 16" width="12" height="12" fill="currentColor" aria-hidden="true">
        {shape.map((p, i) => <path key={i} d={p.d} fillRule={p.fillRule} />)}
      </svg>
    </span>
  );
};

export default TypeIcon;
